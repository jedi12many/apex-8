// Converts a story's pictures (stories/<name>.js pictures) into C64 multicolor bitmaps of any size
// (art/picture.js cells) and writes them as stories/<name>-pictures.js, which the browser and the C64
// build both load: per picture { cw, ch, bg, bitmap, screen, colram } (base64), plus a PNG of each in
// stories/out/ to look at. Needs ffmpeg; run it again when a picture changes.
//
//   node c64/story/pictures.js <story name>
const fs = require('fs'), path = require('path');
const ART = require('../../art/picture.js');

const root = path.join(__dirname, '..', '..');

function convert(name) {
  const story = require(path.join(root, 'stories', `${name}.js`));
  const out = {};
  fs.mkdirSync(path.join(root, 'stories', 'out'), { recursive: true });
  for (const [id, p] of Object.entries(story.pictures)) {
    const [cw, ch] = p.cells, filters = [];
    if (p.crop) filters.push(`crop=${p.crop[2]}:${p.crop[3]}:${p.crop[0]}:${p.crop[1]}`);
    filters.push(`eq=brightness=${p.bright || 0}:saturation=${p.saturation || 1}:gamma=${p.gamma || 1}`);
    const rgb = ART.load(path.join(root, p.file), 4 * cw, 8 * ch, filters);
    const c = ART.cells(rgb, cw, ch, p.dither === undefined ? 30 : p.dither);
    const b64 = a => Buffer.from(a).toString('base64');
    out[id] = { cw, ch, bg: c.bg, bitmap: b64(c.bitmap), screen: b64(c.screen), colram: b64(c.colram) };
    // a PNG to look at: each fat pixel 2 wide
    const W = 8 * cw, H = 8 * ch, rgba = new Uint8Array(W * H * 3);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) rgba.set(ART.PAL[c.px[y * 4 * cw + (x >> 1)]], (y * W + x) * 3);
    const { spawnSync } = require('child_process');
    spawnSync('ffmpeg', ['-v', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', `${W}x${H}`, '-i', '-', '-frames:v', '1',
      path.join(root, 'stories', 'out', `${name}-${id}.png`)], { input: Buffer.from(rgba) });
    console.log(`${name} ${id}: ${cw} x ${ch} cells, ${c.bitmap.length + 2 * cw * ch} bytes on the C64`);
  }
  const js = `// Generated by c64/story/pictures.js from stories/${name}.js: do not edit.\n` +
    `(function (root, pictures) {\n  if (typeof module === 'object' && module.exports) module.exports = pictures;\n` +
    `  else (root.APEXPICTURES = root.APEXPICTURES || {})[${JSON.stringify(name)}] = pictures;\n` +
    `})(typeof self !== 'undefined' ? self : this, ${JSON.stringify(out, null, 1)});\n`;
  fs.writeFileSync(path.join(root, 'stories', `${name}-pictures.js`), js);
}

// A picture's bytes from its stored form.
function decode(p) {
  const d = s => Uint8Array.from(Buffer.from(s, 'base64'));
  return { cw: p.cw, ch: p.ch, bg: p.bg, bitmap: d(p.bitmap), screen: d(p.screen), colram: d(p.colram) };
}

module.exports = { convert, decode };

if (require.main === module) {
  const name = process.argv[2];
  if (!name) { console.error('usage: node c64/story/pictures.js <story name>'); process.exit(2); }
  convert(name);
}
